// Example generation grounded in the vault. The skill never invents APIs: every call in a generated
// example comes from a symbol or operation recorded in the vault (with its source). The script
// produces a deterministic scaffold + validation; the agent may extend it, but must keep the
// "verified symbols only" rule and re-run validation (see references/examples.md).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import type { Question } from './types.ts';
import { readVault } from './vault.ts';
import { loadManifest, vgPaths } from './state.ts';
import { Writer } from './fsutil.ts';
import { assertWritable } from './safety.ts';
import { fence, nowIso, slugify, toPosix, VgError } from './util.ts';

export interface ExampleRequest {
  vaultDir: string;
  cwd: string;
  project?: string;
  goal?: string;
  kind?: 'snippet' | 'app';
  output?: string;
  answers: Record<string, string>;
  validate: boolean;
  dryRun: boolean;
  force: boolean;
}
export interface ExampleResult {
  status: 'done' | 'needs_input';
  questions: Question[];
  outDir?: string;
  files: string[];
  usedSymbols: { name: string; signature: string; note: string; source: string }[];
  validation: { step: string; ran: boolean; passed?: boolean; output?: string }[];
  validated?: boolean;
  notes: string[];
}

interface ProjectNoteInfo {
  id: string;
  title: string;
  path: string;
  ecosystem: string;
  kind: string;
  version?: string;
  manifestPath?: string;
  sourcePath?: string;
  symbols: { name: string; kind: string; signature: string; file: string; note: string }[];
  scripts: Record<string, string>;
  packageName: string;
}

function projectsFromVault(vaultDir: string): ProjectNoteInfo[] {
  const manifest = loadManifest(vaultDir);
  if (!manifest) throw new VgError('E_NO_VAULT', 'examples needs a vault generated by vault-generator');
  const notes = readVault(vaultDir).filter((n) => n.hasVg && n.access !== 'restricted');
  const out: ProjectNoteInfo[] = [];
  for (const n of notes.filter((x) => x.type === 'project' || (x.type === 'example' && String(x.key).startsWith('project:')))) {
    const key = String(n.key ?? '');
    const m = /^project:([^:]+):(.+)$/.exec(key);
    if (!m) continue;
    const mp = manifest.context.projects.find((p) => p.path === `${m[1]}:${m[2]}`);
    const src = manifest.sources.find((s) => s.id === m[1]);
    const related = notes.filter((x) => x.key === key || (typeof x.fm.project === 'string' && x.fm.project.includes(n.title)) || (x.type === 'module' && String(x.key).startsWith(`module:${m[1]}:${m[2] === '.' ? '' : m[2]}`)));
    const symbols: ProjectNoteInfo['symbols'] = [];
    for (const r of related) {
      const lines = r.body.split('\n');
      for (let i = 0; i < lines.length; i++) {
        const h = /^#{3,4}\s+(.+?)\s+·\s+([\w-]+)\s*$/.exec(lines[i]);
        if (!h) continue;
        let sig = '';
        let file = '';
        for (let j = i + 1; j < Math.min(lines.length, i + 14); j++) {
          if (!sig && /^```/.test(lines[j])) sig = lines[j + 1] ?? '';
          const d = /\*(?:Defined in|Definido en)\* `([^`]+)`/.exec(lines[j]);
          if (d) {
            file = d[1];
            break;
          }
        }
        symbols.push({ name: h[1], kind: h[2], signature: sig, file, note: r.path });
      }
    }
    const scripts: Record<string, string> = {};
    const sm = /## (?:Scripts)\n\n([\s\S]*?)(?:\n## |\n> \[!info\])/m.exec(n.body);
    if (sm) for (const row of sm[1].split('\n').slice(2)) {
      const c = row.split('|').map((x) => x.trim().replace(/^`|`$/g, ''));
      if (c[1]) scripts[c[1]] = c[2];
    }
    out.push({
      id: mp?.id ?? slugify(n.title), title: n.title, path: n.path, ecosystem: mp?.ecosystem ?? 'unknown', kind: mp?.kind ?? 'unknown', version: mp?.version,
      manifestPath: src?.path !== null && src ? path.resolve(vaultDir, src.path, m[2] === '.' ? '' : m[2]) : undefined, sourcePath: src?.path ?? undefined,
      symbols: uniqBy(symbols, (s) => `${s.name}|${s.kind}`), scripts, packageName: n.title,
    });
  }
  return out;
}
const uniqBy = <T>(a: T[], f: (x: T) => string) => {
  const seen = new Set<string>();
  return a.filter((x) => (seen.has(f(x)) ? false : (seen.add(f(x)), true)));
};

export function generateExample(req: ExampleRequest): ExampleResult {
  const projects = projectsFromVault(req.vaultDir).filter((p) => p.kind !== 'example');
  const questions: Question[] = [];
  const res: ExampleResult = { status: 'done', questions, files: [], usedSymbols: [], validation: [], notes: [] };
  const target = req.project ?? req.answers['example-project'];
  const candidates = projects.filter((p) => p.symbols.some((s) => ['function', 'class', 'component', 'const'].includes(s.kind)));
  let proj = target ? projects.find((p) => p.id === target || p.title === target) : candidates.length === 1 ? candidates[0] : undefined;
  if (target && !proj) throw new VgError('E_SCOPE', `Unknown project "${target}". Known: ${projects.map((p) => p.id).join(', ')}`);
  if (!proj) {
    questions.push({
      id: 'example-project', kind: 'example-requirements', blocking: true,
      prompt: 'Which project should the example demonstrate?', why: 'The example must use the real, documented API of one project.',
      options: candidates.slice(0, 8).map((p) => ({ value: p.id, label: `${p.title} (${p.kind}, ${p.symbols.length} documented symbols)` })),
    });
  }
  const goal = req.goal ?? req.answers['example-goal'];
  if (!goal) questions.push({ id: 'example-goal', kind: 'example-requirements', blocking: true, freeText: true, prompt: 'What should the example show (one sentence)?', why: 'Without a goal the example would be arbitrary; the goal selects which documented APIs to use.', options: [] });
  const kind = req.kind ?? (req.answers['example-kind'] as 'snippet' | 'app' | undefined);
  if (!kind) questions.push({ id: 'example-kind', kind: 'example-requirements', blocking: true, prompt: 'Snippet or runnable mini-application?', why: 'A runnable app needs a directory, dependencies and a build; a snippet does not.', options: [{ value: 'snippet', label: 'Code snippet (single file)' }, { value: 'app', label: 'Runnable example project (directory with manifest, README, smoke test)' }], default: 'snippet' });
  if (questions.length) return { ...res, status: 'needs_input' };
  proj = proj!;
  if (!['node', 'python'].some((e) => proj!.ecosystem.includes(e))) {
    throw new VgError('E_UNSUPPORTED', `Example scaffolding is implemented for Node.js and Python projects; "${proj.title}" is ${proj.ecosystem}. The documented API is in ${proj.path}; write the example by hand from it.`);
  }
  // pick verified symbols relevant to the goal
  const words = goal!.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter((w) => w.length > 2);
  const callable = proj.symbols.filter((s) => ['function', 'class', 'component', 'const'].includes(s.kind));
  const scored = callable.map((s) => ({ s, score: words.filter((w) => `${s.name} ${s.signature}`.toLowerCase().includes(w)).length })).sort((a, b) => b.score - a.score || a.s.name.localeCompare(b.s.name));
  const chosen = (scored.filter((x) => x.score > 0).length ? scored.filter((x) => x.score > 0) : scored).slice(0, 3).map((x) => x.s);
  if (!chosen.length) throw new VgError('E_NO_KNOWLEDGE', `The vault has no documented public functions/classes for ${proj.title}; an example cannot be grounded.`);
  res.usedSymbols = chosen.map((s) => ({ name: s.name, signature: s.signature, note: s.note, source: s.file }));
  const isTs = chosen.some((s) => /:\s*\w/.test(s.signature) || /\.tsx?:/.test(s.file));
  const py = proj.ecosystem.includes('python');
  const outDir = path.resolve(req.cwd, req.output ?? path.join('examples', slugify(`${proj.id}-${goal}`, 50)));
  assertWritable(outDir, [req.cwd]);
  if (outDir.startsWith(path.resolve(req.vaultDir) + path.sep)) throw new VgError('E_DEST', 'Examples are not stored inside the vault; choose an --output outside it (the vault links to it).');
  if (fs.existsSync(outDir) && fs.readdirSync(outDir).length && !req.force) throw new VgError('E_EXISTS', `${outDir} is not empty; pass --force or another --output`);
  const w = new Writer([req.cwd], req.dryRun);
  const rel = toPosix(path.relative(outDir, proj.manifestPath ?? req.cwd)) || '.';
  const header = (c: string) => `${c} Example generated by vault-generator from documented APIs only.\n${c} Goal: ${goal}\n${c} Project: ${proj!.title}${proj!.version ? `@${proj!.version}` : ''}\n${c} Uses: ${chosen.map((s) => `${s.name} (${s.file || s.note})`).join('; ')}\n`;
  const calls = chosen.map((s) => callFor(s, py));
  const files: Record<string, string> = {};
  if (py) {
    const mod = proj.packageName.replace(/-/g, '_');
    files['example.py'] = `${header('#')}\nfrom ${mod} import ${chosen.map((s) => s.name).join(', ')}\n\n\ndef main() -> None:\n${calls.map((c) => `    ${c}`).join('\n')}\n\n\nif __name__ == "__main__":\n    main()\n`;
    if (kind === 'app') {
      files['README.md'] = readme(proj, goal!, chosen, 'python example.py', rel, true);
      files['requirements.txt'] = `# install the documented project from its local path\n-e ${rel}\n`;
    }
  } else {
    const ext = isTs ? 'ts' : 'mjs';
    const imp = `import { ${chosen.map((s) => s.name).join(', ')} } from '${proj.packageName}';`;
    files[`example.${ext}`] = `${header('//')}\n${imp}\n\n${calls.join('\n')}\n`;
    if (kind === 'app') {
      files['package.json'] = `${JSON.stringify({ name: slugify(`${proj.id}-example`), private: true, type: 'module', description: `Example: ${goal}`, scripts: { start: isTs ? `node example.${ext}` : `node example.${ext}`, check: isTs ? 'tsc --noEmit' : `node --check example.${ext}` }, dependencies: { [proj.packageName]: `file:${rel}` }, ...(isTs ? { devDependencies: { typescript: '^5' } } : {}) }, null, 2)}\n`;
      if (isTs) files['tsconfig.json'] = `${JSON.stringify({ compilerOptions: { target: 'ES2022', module: 'nodenext', moduleResolution: 'nodenext', strict: true, noEmit: true, skipLibCheck: true } }, null, 2)}\n`;
      files['README.md'] = readme(proj, goal!, chosen, 'npm install && npm start', rel, false);
    }
  }
  files['vg-example.json'] = `${JSON.stringify({ generatedBy: 'vault-generator', at: nowIso(), goal, project: proj.title, projectVersion: proj.version, vaultNote: proj.path, usedSymbols: res.usedSymbols, validated: false }, null, 2)}\n`;
  for (const [f, c] of Object.entries(files)) {
    w.write(path.join(outDir, f), c);
    res.files.push(f);
  }
  res.outDir = outDir;
  // validation: syntax checks that can run without installing anything; build/run only when explicitly asked
  const main = res.files.find((f) => f.startsWith('example.'))!;
  if (!req.dryRun) {
    if (main.endsWith('.mjs')) res.validation.push(run('node --check', 'node', ['--check', path.join(outDir, main)]));
    else if (main.endsWith('.ts')) res.validation.push(run('node --check (type-stripped)', 'node', ['--experimental-strip-types', '--check', path.join(outDir, main)]));
    else if (main.endsWith('.py')) {
      const pyBin = whichPython();
      res.validation.push(pyBin ? run(`${pyBin} -m py_compile`, pyBin, ['-m', 'py_compile', path.join(outDir, main)]) : { step: 'python -m py_compile', ran: false, output: 'Python not found on PATH' });
    }
    if (req.validate && kind === 'app' && !py) {
      res.validation.push(run('npm install', process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--no-audit', '--no-fund'], outDir, 300000));
      if (res.validation.at(-1)?.passed) res.validation.push(run('npm start', process.platform === 'win32' ? 'npm.cmd' : 'npm', ['start'], outDir, 120000));
    } else if (kind === 'app') res.notes.push('Dependencies were not installed and the app was not run (pass --validate to run install + start). It is NOT validated yet.');
    // an app is validated only when it was actually installed and run; a snippet when its check passed
    const ranApp = res.validation.some((v) => v.step === 'npm start');
    const validated = res.validation.length > 0 && res.validation.every((v) => v.ran && v.passed) && (kind !== 'app' || ranApp);
    res.validated = validated;
    const meta = JSON.parse(files['vg-example.json']);
    meta.validated = validated;
    meta.validation = res.validation.map((v) => ({ step: v.step, ran: v.ran, passed: v.passed }));
    w.write(path.join(outDir, 'vg-example.json'), `${JSON.stringify(meta, null, 2)}\n`);
    recordExampleInVault(req.vaultDir, proj, outDir, goal!, validated, req.cwd);
  }
  return res;
}

function callFor(s: { name: string; kind: string; signature: string }, py: boolean): string {
  const params = /\(([^)]*)\)/.exec(s.signature)?.[1] ?? '';
  const args = params
    .split(',')
    .map((p) => p.trim())
    .filter((p) => p && !p.startsWith('self') && !p.startsWith('*') && !/^\.\.\./.test(p))
    .map((p) => {
      const name = p.split(/[:=?]/)[0].trim();
      const type = (/:\s*([^=]+)/.exec(p)?.[1] ?? '').trim().toLowerCase();
      if (/=/.test(p) || /\?/.test(p.split(':')[0])) return undefined; // optional: omit
      const v = /number|int|float/.test(type) ? '1' : /bool/.test(type) ? (py ? 'True' : 'true') : /string|str/.test(type) ? `'${name}'` : /\[\]|array|list/.test(type) ? '[]' : py ? 'None' : 'undefined /* TODO: provide a value */';
      return v;
    })
    .filter((x): x is string => x !== undefined);
  const call = s.kind === 'class' ? `${py ? '' : 'new '}${s.name}(${args.join(', ')})` : `${s.name}(${args.join(', ')})`;
  return py ? `print(${call})  # ${s.signature.replace(/\s+/g, ' ').slice(0, 80)}` : `console.log(${call}); // ${s.signature.replace(/\s+/g, ' ').slice(0, 80)}`;
}
function readme(p: ProjectNoteInfo, goal: string, syms: ProjectNoteInfo['symbols'], start: string, rel: string, py: boolean): string {
  return `# Example: ${goal}\n\nDemonstrates **${p.title}**${p.version ? ` \`${p.version}\`` : ''} using only APIs documented in the vault.\n\n## Run\n\n${fence(start, 'sh')}\n\nThe documented project is referenced from its local path (\`${rel}\`)${py ? '' : ' via a `file:` dependency'}.\n\n## APIs used\n\n${syms.map((s) => `- \`${s.name}\` — ${fence(s.signature, py ? 'python' : 'ts').replace(/\n/g, ' ')} (${s.file || s.note})`).join('\n')}\n\n## Status\n\nSee \`vg-example.json\` for validation results. Placeholder arguments marked \`TODO\` must be replaced with real values.\n`;
}
function run(step: string, cmd: string, args: string[], cwd?: string, timeout = 60000): ExampleResult['validation'][number] {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', timeout, shell: process.platform === 'win32' && cmd.endsWith('.cmd') });
  if (r.error) return { step, ran: false, output: r.error.message };
  return { step, ran: true, passed: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim().slice(-2000) };
}
function whichPython(): string | undefined {
  for (const c of ['python3', 'python', 'py']) {
    const r = spawnSync(c, ['--version'], { encoding: 'utf8' });
    if (r.status === 0 && /Python 3/.test(`${r.stdout}${r.stderr}`)) return c;
  }
  return undefined;
}

/** The vault references the example (it never stores the project itself). */
function recordExampleInVault(vaultDir: string, p: ProjectNoteInfo, outDir: string, goal: string, validated: boolean, cwd: string): void {
  const w = new Writer([vaultDir]);
  const file = path.join(vgPaths(vaultDir).dir, 'examples.json');
  let list: unknown[] = [];
  try {
    list = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    list = [];
  }
  const rel = toPosix(path.relative(vaultDir, outDir));
  list = (list as { path: string }[]).filter((e) => e.path !== rel);
  list.push({ path: rel, project: p.title, goal, validated, at: nowIso(), from: toPosix(path.relative(vaultDir, cwd)) || '.' });
  w.writeJson(file, list);
}
