// Persistent context: manifest (shareable, no absolute paths, no secrets), state (hashes, stable ids,
// merge bases), local bindings (machine-specific absolute paths, never committed), backups.
import fs from 'node:fs';
import path from 'node:path';
import type { ConflictRecord, Decision, Manifest } from './types.ts';
import { Writer, readJsonFile } from './fsutil.ts';
import { hasPrivateAbsolutePath, isInside, safeJoin } from './safety.ts';
import { VG_DIR } from './vault.ts';
import { nowIso, sha256, shortHash, slugify, stableStringify, toPosix, VgError } from './util.ts';

export const TOOL_VERSION = '1.0.0';

export interface NoteState {
  key: string;
  path: string;
  /** hash of the region content as last generated by vault-generator */
  genHash: string;
  managedFm: Record<string, unknown>;
  origin: string;
  sources: string[];
  createdRun: string;
  updatedRun: string;
}
export interface State {
  schema: 1;
  notes: Record<string, NoteState>;
  /** key → id, including old keys of renamed sources (keeps ids stable across moves) */
  keys: Record<string, string>;
  files: Record<string, { hash: string; size: number; mtimeMs: number }>;
  contracts: Record<string, Record<string, string>>;
  projects: Record<string, { name: string; deps: string[]; kind: string }>;
  runs: { id: string; mode: string; at: string; summary: Record<string, number> }[];
}

export const emptyState = (): State => ({ schema: 1, notes: {}, keys: {}, files: {}, contracts: {}, projects: {}, runs: [] });

export interface VgPaths {
  vault: string;
  dir: string;
  manifest: string;
  state: string;
  local: string;
  index: string;
  base: string;
  backups: string;
  conflicts: string;
  cache: string;
  trash: string;
}
export function vgPaths(vaultDir: string): VgPaths {
  const dir = path.join(vaultDir, VG_DIR);
  return {
    vault: vaultDir, dir, manifest: path.join(dir, 'manifest.json'), state: path.join(dir, 'state.json'), local: path.join(dir, 'local.json'),
    index: path.join(dir, 'index.sqlite'), base: path.join(dir, 'base'), backups: path.join(dir, 'backups'), conflicts: path.join(dir, 'conflicts'),
    cache: path.join(dir, 'cache'), trash: path.join(dir, 'trash'),
  };
}

export const GITIGNORE = ['# vault-generator local data (machine specific or derived)', 'local.json', 'index.sqlite', 'index.sqlite-*', 'cache/', 'backups/', 'trash/', ''].join('\n');

export function loadManifest(vaultDir: string): Manifest | undefined {
  const m = readJsonFile<Manifest>(vgPaths(vaultDir).manifest);
  if (!m) return undefined;
  if (m.schema !== 1) throw new VgError('E_MANIFEST', `Unsupported manifest schema ${String((m as { schema?: unknown }).schema)}`);
  return m;
}
export function loadState(vaultDir: string): State {
  return { ...emptyState(), ...(readJsonFile<State>(vgPaths(vaultDir).state) ?? {}) };
}
export interface LocalBindings {
  sources: Record<string, string>;
}
export function loadLocal(vaultDir: string): LocalBindings {
  return { sources: {}, ...(readJsonFile<LocalBindings>(vgPaths(vaultDir).local) ?? {}) };
}

/** Stable, reproducible scope identifier: depends only on the source labels. */
export function scopeIdFor(labels: string[]): string {
  return `scope-${shortHash([...labels].sort().join('+'), 12)}`;
}
export function noteIdFor(scopeId: string, key: string): string {
  return `vg-${shortHash(`${scopeId}|${key}`, 10)}`;
}

/** Persistable posix path from the vault to a source; null when not expressible (other drive). */
export function relFromVault(vaultDir: string, abs: string): string | null {
  const rel = path.relative(vaultDir, abs);
  if (path.isAbsolute(rel) || /^[a-zA-Z]:/.test(rel)) return null;
  return toPosix(rel) || '.';
}
export function resolveSourcePath(vaultDir: string, rel: string | null, id: string, local: LocalBindings): string | undefined {
  if (local.sources[id]) return local.sources[id];
  if (rel === null) return undefined;
  return path.resolve(vaultDir, rel);
}

/** Refuse to persist absolute private paths or secrets in shareable files. */
export function assertShareable(obj: unknown, what: string): void {
  const s = stableStringify(obj);
  if (hasPrivateAbsolutePath(s)) throw new VgError('E_PRIVACY', `Refusing to persist an absolute private path in ${what}`);
}

// ───────────── backups & journal (recovery) ─────────────
export interface JournalEntry {
  action: 'create' | 'update' | 'move' | 'mark-stale' | 'trash' | 'restore';
  path: string;
  from?: string;
  /** backup copy, relative to the run's backup dir */
  backup?: string;
}
export class RunJournal {
  runId: string;
  entries: JournalEntry[] = [];
  private paths: VgPaths;
  private writer: Writer;
  constructor(paths: VgPaths, writer: Writer, runId: string) {
    this.paths = paths;
    this.writer = writer;
    this.runId = runId;
  }
  get dir(): string {
    return path.join(this.paths.backups, this.runId);
  }
  /** Copy an existing vault file into this run's backup before it is modified or moved. */
  backup(vaultRel: string): string | undefined {
    const abs = safeJoin(this.paths.vault, vaultRel);
    if (!fs.existsSync(abs)) return undefined;
    const rel = toPosix(vaultRel);
    const dst = path.join(this.dir, 'files', rel);
    if (!this.writer.dryRun && fs.existsSync(dst)) return rel;
    this.writer.copy(abs, dst);
    return rel;
  }
  record(e: JournalEntry): void {
    this.entries.push(e);
  }
  save(mode: string): void {
    if (!this.entries.length) return;
    this.writer.writeJson(path.join(this.dir, 'journal.json'), { runId: this.runId, mode, at: nowIso(), entries: this.entries });
  }
}

export function listBackups(paths: VgPaths): { runId: string; mode: string; at: string; entries: number }[] {
  if (!fs.existsSync(paths.backups)) return [];
  return fs
    .readdirSync(paths.backups)
    .map((id) => {
      const j = readJsonFile<{ mode: string; at: string; entries: JournalEntry[] }>(path.join(paths.backups, id, 'journal.json'));
      return j ? { runId: id, mode: j.mode, at: j.at, entries: j.entries.length } : undefined;
    })
    .filter((x): x is NonNullable<typeof x> => !!x)
    .sort((a, b) => a.runId.localeCompare(b.runId));
}
export function pruneBackups(paths: VgPaths, writer: Writer, keep: number): number {
  const all = listBackups(paths);
  const remove = all.slice(0, Math.max(0, all.length - keep));
  for (const r of remove) writer.deleteOwned(path.join(paths.backups, r.runId), paths.backups);
  return remove.length;
}

export function newManifest(args: { name: string; scopeId: string; language: 'en' | 'es'; depth: Manifest['depth']; placement: 'root' | 'subfolder'; folder: string; workspaceRoot: string }): Manifest {
  return {
    schema: 1, scopeId: args.scopeId, name: args.name, createdWith: { tool: 'vault-generator', version: TOOL_VERSION }, language: args.language, depth: args.depth,
    vault: { placement: args.placement, folder: args.folder }, workspaceRoot: args.workspaceRoot,
    context: { kind: 'unknown', tools: [], repositories: [], projects: [], docSources: [], relations: [], technologies: {}, versions: [] },
    sources: [], scopeSelection: { mode: 'all', projects: [] }, layout: { strategy: '', folders: {} }, indexing: { engine: 'sqlite-fts5', notes: 0, contentHash: '' },
    sync: { strategy: 'hash+mtime', lastRunId: '' }, decisions: {}, conflicts: [], transformers: [], trustedPlugins: {},
  };
}

export function recordDecision(m: Manifest, id: string, answer: string, prompt?: string, assumed = false): void {
  const d: Decision & { assumed?: boolean } = { answer, answeredAt: nowIso(), prompt };
  if (assumed) d.assumed = true;
  m.decisions[id] = d;
}

export function conflictId(noteId: string, runId: string): string {
  return `conflict-${shortHash(`${noteId}|${runId}`, 8)}`;
}
export function addConflict(m: Manifest, c: ConflictRecord): void {
  m.conflicts = m.conflicts.filter((x) => x.noteId !== c.noteId || x.kind !== c.kind);
  m.conflicts.push(c);
}

export function saveAll(writer: Writer, paths: VgPaths, manifest: Manifest, state: State, local: LocalBindings): void {
  assertShareable(manifest, 'manifest.json');
  assertShareable(state, 'state.json');
  writer.writeJson(paths.manifest, manifest);
  writer.writeJson(paths.state, state);
  if (Object.keys(local.sources).length) writer.writeJson(paths.local, local);
  const gi = path.join(paths.dir, '.gitignore');
  if (!fs.existsSync(gi)) writer.write(gi, GITIGNORE);
}

export function baseSnapshotPath(paths: VgPaths, id: string): string {
  return path.join(paths.base, `${id}.md`);
}
export function readBase(paths: VgPaths, id: string): string | undefined {
  try {
    return fs.readFileSync(baseSnapshotPath(paths, id), 'utf8');
  } catch {
    return undefined;
  }
}

/** Locate a vault managed by vault-generator: explicit path, cwd itself, or a generated vault below cwd. */
export function findVault(cwd: string, explicit?: string, generatedBelow: string[] = []): { dir: string; exists: boolean; managed: boolean } | undefined {
  if (explicit) {
    const dir = path.resolve(cwd, explicit);
    return { dir, exists: fs.existsSync(dir), managed: fs.existsSync(vgPaths(dir).manifest) };
  }
  if (fs.existsSync(vgPaths(cwd).manifest)) return { dir: cwd, exists: true, managed: true };
  if (generatedBelow.length === 1) {
    const dir = path.resolve(cwd, generatedBelow[0]);
    if (isInside(cwd, dir)) return { dir, exists: true, managed: true };
  }
  return undefined;
}

export const sourceIdFor = (label: string, taken: Set<string>): string => {
  let id = slugify(label, 40);
  for (let n = 2; taken.has(id); n++) id = `${slugify(label, 36)}-${n}`;
  taken.add(id);
  return id;
};
export const contentHashOf = (items: string[]): string => sha256(items.sort().join('\n')).slice(0, 16);
